import { defineConfig, globalIgnores } from "eslint/config";
import nextVitals from "eslint-config-next/core-web-vitals";
import nextTs from "eslint-config-next/typescript";

// Spec §10: staff, portal, and print code must not import from each other.
// Shared code belongs in components/, domain/, hooks/, lib/, or api/.
function crossSideImportRule(forbidden) {
  return {
    "no-restricted-imports": [
      "error",
      {
        patterns: forbidden.map((side) => ({
          group: [`@/${side}/*`, `@/${side}`],
          message: `Cross-side import: this file must not import from src/${side}/. Move shared code to components/, domain/, hooks/, lib/, or api/ instead.`,
        })),
      },
    ],
  };
}

const eslintConfig = defineConfig([
  ...nextVitals,
  ...nextTs,
  // Override default ignores of eslint-config-next.
  globalIgnores([
    // Default ignores of eslint-config-next:
    ".next/**",
    "out/**",
    "build/**",
    "next-env.d.ts",
    // Generated by `npx msw init` — not hand-written, shouldn't be linted.
    "public/mockServiceWorker.js",
  ]),
  {
    files: ["src/staff/**/*.{ts,tsx}", "src/app/app/**/*.{ts,tsx}"],
    rules: crossSideImportRule(["portal", "print"]),
  },
  {
    files: ["src/portal/**/*.{ts,tsx}", "src/app/portal/**/*.{ts,tsx}"],
    rules: crossSideImportRule(["staff", "print"]),
  },
  {
    files: ["src/print/**/*.{ts,tsx}", "src/app/print/**/*.{ts,tsx}"],
    rules: crossSideImportRule(["staff", "portal"]),
  },
]);

export default eslintConfig;
